"""R130 HOLD: fail-closed preprocessed-backup upgrade admission in R112.

Spicetify v2.46.7's src/cmd/apply.go exits nonzero when [Backup].with does not
exactly match the running CLI's version. Current R112 swaps CLI and invokes
'apply --no-restart', so a 2.46.4 backup cannot be applied by 2.46.7.
Before a full preprocessed backup + Spotify Apps rollback domain is implemented
and accepted on real Windows, any version-changing auto-upgrade must remain OFF.

Hosted Windows only. Does not update user installation or public main.
"""
from __future__ import annotations
import hashlib
import os
from pathlib import Path

HERE=Path(__file__).resolve().parent
SOURCE=HERE/"out/private-stable-ahead-R112/spotify-control.ps1"
EXPECTED="beb850064670c078a679585ace25f8071daa88c0b264185c03ef3364329b431b"
OUTPUT=HERE/"out/private-preprocessed-migration-gate-R130/spotify-control.ps1"

HELPER=r"""
function Get-SpicetifyBackupMigrationClass {
    param([string]$InstalledVersion,[string]$TargetVersion,[string]$BackupWith)
    if ([string]::IsNullOrWhiteSpace($InstalledVersion) -or
        [string]::IsNullOrWhiteSpace($TargetVersion)) {
        return 'VERSION_IDENTITY_UNVERIFIED'
    }
    if ([string]::IsNullOrWhiteSpace($BackupWith)) {
        return 'BACKUP_PREPROCESSOR_UNVERIFIED'
    }
    if ($BackupWith -cne $InstalledVersion) {
        return 'BACKUP_PREPROCESSOR_NOT_CURRENT_CLI'
    }
    if ($TargetVersion -cne $InstalledVersion) {
        return 'VERSION_CHANGE_REQUIRES_ATOMIC_BACKUP_REPROCESSING'
    }
    return 'BACKUP_PREPROCESSOR_CURRENT'
}
"""

ANCHOR="""    if ($cmp -eq 0 -and -not $ForceReinstall) { return [pscustomobject]@{ Changed=$false; Status='already-current'; Transaction=$null; Latest=$latest } }
"""
GUARD="""    if ($cmp -eq 0 -and -not $ForceReinstall) { return [pscustomobject]@{ Changed=$false; Status='already-current'; Transaction=$null; Latest=$latest } }
    # Do NOT swap a new CLI while its preprocessed assets were generated by
    # the old CLI. Upstream Apply() exits 1 before checking Spotify state when
    # Backup.with != running CLI version. A valid migration must snapshot and
    # restore Spotify Apps + Roaming Spicetify Backup/config, not just the exe.
    $spiceConfig=Get-ConfigPath
    if ([string]::IsNullOrWhiteSpace([string]$spiceConfig)) {
        throw 'R130_BACKUP_PREPROCESSOR_CONFIG_UNVERIFIED_NO_ROOT_MUTATION'
    }
    $backupWith=Get-IniSectionValue -Path $spiceConfig -Section 'Backup' -Key 'with'
    $upgradeClass=Get-SpicetifyBackupMigrationClass -InstalledVersion $currentVersion -TargetVersion ([string]$latest.Version) -BackupWith ([string]$backupWith)
    if ($upgradeClass -cne 'BACKUP_PREPROCESSOR_CURRENT') {
        throw ('R130_PREPROCESSED_BACKUP_MIGRATION_HOLD:'+$upgradeClass)
    }
"""

def check(cond: bool,reason:str)->None:
    if not cond: raise RuntimeError("R130_"+reason)

def sha(data:bytes)->str:
    return hashlib.sha256(data).hexdigest()

def main()->None:
    check(os.getenv("GITHUB_ACTIONS")=="true" and
        os.getenv("RUNNER_OS")=="Windows" and
        os.getenv("RUNNER_ENVIRONMENT")=="github-hosted","HOSTED_WINDOWS_ONLY")
    raw=SOURCE.read_bytes()
    check(sha(raw)==EXPECTED,"EXACT_R112_SOURCE_SHA_MISMATCH")
    newline="\r\n" if b"\r\n" in raw else "\n"
    bom=b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
    text=raw.decode("utf-8-sig").replace("\r\n","\n")
    start=text.index("\nfunction Start-SpicetifyCliTransaction {")+1
    end=text.index("\nfunction ",start+len("\nfunction Start-SpicetifyCliTransaction {"))
    body=text[start:end]
    check(body.count(ANCHOR)==1,"ANCHOR_NOT_EXACT")
    check("Get-SpicetifyBackupMigrationClass" not in text,"HELPER_ALREADY_PRESENT")
    revised=body.replace(ANCHOR,GUARD,1)
    check(revised.count("R130_PREPROCESSED_BACKUP_MIGRATION_HOLD:")==1,"GUARD_NOT_UNIQUE")
    check(revised.index("R130_PREPROCESSED_BACKUP_MIGRATION_HOLD:") <
          revised.index("$id = (Get-Date -Format"),"GUARD_MUST_BEFORE_STAGING")
    candidate=text[:start]+revised+text[end:]
    target="\nfunction Start-SpicetifyCliTransaction {"
    check(candidate.count(target)==1,"START_FUNCTION_NOT_UNIQUE")
    candidate=candidate.replace(target,HELPER+target,1)
    # Full source exact reversibility and byte preservation outside target
    reverted=candidate.replace(HELPER+target,target,1).replace(GUARD,ANCHOR,1)
    check(reverted==text,"EXACT_REPLAY_MISMATCH")
    out=bom+candidate.replace("\n",newline).encode("utf-8")
    check(out!=raw,"CANDIDATE_NO_CHANGE")
    check(not OUTPUT.exists(),"EXISTING_TARGET_NO_OVERWRITE")
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    with OUTPUT.open("xb") as fh:fh.write(out)
    check(sha(OUTPUT.read_bytes())==sha(out),"OUTPUT_SHA_MISMATCH")
    print("R130_R112_EXACT_SHA=PASS")
    print("R130_BACKUP_WITH_MIGRATION_GATE_BEFORE_ANY_ROOT_WRITE=PASS")
    print("R130_ONLY_START_FUNCTION_AND_NEW_PURE_HELPER=PASS")
    print("R130_PUBLIC_MAIN_AND_OWNER_INSTALLATION=UNCHANGED")
    print("R130_CANDIDATE_SHA256="+sha(out))

if __name__=="__main__":
    main()
